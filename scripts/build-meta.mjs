function parseFrontmatter(raw) {
  const match = raw.match(/^---\r?\n([\s\S]*?)\r?\n---\r?\n?([\s\S]*)$/);
  if (!match) throw new Error('Missing frontmatter');
  const data = {};
  for (const line of match[1].split(/\r?\n/)) {
    const idx = line.indexOf(':');
    if (idx === -1) continue;
    const key = line.slice(0, idx).trim();
    let value = line.slice(idx + 1).trim();
    if (value.startsWith('[') && value.endsWith(']')) {
      value = value
        .slice(1, -1)
        .split(',')
        .map((v) => v.trim().replace(/^['"]|['"]$/g, ''))
        .filter(Boolean);
    }
    data[key] = value;
  }
  return { data, body: match[2] };
}

const articlesDir = join(root, 'content', 'articles');
const files = (await readdir(articlesDir)).filter((f) => f.endsWith('.md')).sort();
const articles = [];

for (const file of files) {
  const raw = await readFile(join(articlesDir, file), 'utf8');
  const { data, body } = parseFrontmatter(raw);
  const html = await marked.parse(body, { gfm: true });
  articles.push({
    slug: file.replace(/\.md$/, ''),
    title: data.title,
    description: data.description,
    date: data.date,
    tags: Array.isArray(data.tags) ? data.tags : [String(data.tags)],
    readingTime: data.readingTime ?? '5 min read',
    html: html.trim(),
  });
}

articles.sort((a, b) => (a.date < b.date ? 1 : -1));

const generatedTs = `// AUTO-GENERATED by scripts/build-meta.mjs — do not edit by hand.
import { ArticleMeta } from '../../models/profile.models';

export const ARTICLES: ArticleMeta[] = ${JSON.stringify(articles, null, 2)};

export const ARTICLE_BY_SLUG: Record<string, ArticleMeta> = Object.fromEntries(
  ARTICLES.map((a) => [a.slug, a]),
);
`;

const generatedDir = join(root, 'src', 'app', 'core', 'data', 'generated');
await mkdir(generatedDir, { recursive: true });
await writeFile(join(generatedDir, 'articles.generated.ts'), generatedTs, 'utf8');
console.log(`✓ generated articles.generated.ts (${articles.length} articles)`);

const today = new Date().toISOString().slice(0, 10);

// sitemap.xml requires absolute URLs, so it is only generated once
// content/site.config.json has a `siteUrl` set. Until then we skip it with a
// TODO warning — the site still works; only the sitemap signal is deferred.
const siteUrl = (site.siteUrl || '').trim();
const baseForBuild = siteUrl ? siteUrl.replace(/\/+$/, '') : '';
if (!siteUrl) {
  // Remove any stale sitemap from a previous build so we never ship a
  // sitemap pointing at a URL that is no longer configured.
  await rm(join(root, 'public', 'sitemap.xml'), { force: true });
  console.log('⏭  skipped sitemap.xml (TODO: set siteUrl in content/site.config.json)');
} else {
  const urls = [
    ...STATIC_ROUTES.map((r) => ({ loc: `${siteUrl}${r.path}`, lastmod: today, priority: r.priority })),
    ...articles.map((a) => ({
      loc: `${siteUrl}/knowledge/${a.slug}`,
      lastmod: a.date,
      priority: '0.7',
    })),
  ];

  const sitemap = `<?xml version="1.0" encoding="UTF-8"?>
<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">
${urls
  .map(
    (u) => `  <url>
    <loc>${u.loc}</loc>
    <lastmod>${u.lastmod}</lastmod>
    <changefreq>monthly</changefreq>
    <priority>${u.priority}</priority>
  </url>`,
  )
  .join('\n')}
</urlset>
`;
  await writeFile(join(root, 'public', 'sitemap.xml'), sitemap, 'utf8');
  console.log(`✓ generated sitemap.xml (${urls.length} urls)`);
}

